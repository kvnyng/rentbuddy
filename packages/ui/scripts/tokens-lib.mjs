// Pure token -> CSS rendering, shared by build-tokens.mjs and its tests.
// Every token becomes a CSS custom property: color.cyan.500 -> --rb-color-cyan-500.
// References like "{color.ink.900}" become var(--rb-color-ink-900), and must
// name an existing leaf token.

const toVar = (path) => `--rb-${path.join("-")}`;

/** Flattens the token tree into [path, value] leaves. */
const leaves = (node, path = []) =>
  Object.entries(node).flatMap(([key, value]) =>
    typeof value === "object" && value !== null ? leaves(value, [...path, key]) : [[[...path, key], String(value)]],
  );

/**
 * @returns {{ ok: true, css: string, count: number }
 *         | { ok: false, errors: { token: string, ref: string }[] }}
 */
export function renderTokens(tokens) {
  const all = leaves(tokens);
  const known = new Set(all.map(([path]) => path.join(".")));
  const errors = [];
  const lines = all.map(([path, value]) => {
    const resolved = value.replace(/\{([^}]+)\}/g, (_, ref) => {
      if (!known.has(ref)) errors.push({ token: path.join("."), ref });
      return `var(${toVar(ref.split("."))})`;
    });
    return `  ${toVar(path)}: ${resolved};`;
  });
  if (errors.length > 0) return { ok: false, errors };
  const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */\n:root {\n${lines.join("\n")}\n}\n`;
  return { ok: true, css, count: lines.length };
}
