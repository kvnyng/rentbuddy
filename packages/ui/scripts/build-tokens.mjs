// Generates src/tokens/tokens.css from src/tokens/tokens.json.
// Every token becomes a CSS custom property: color.cyan.500 -> --rb-color-cyan-500.
// References like "{color.ink.900}" become var(--rb-color-ink-900).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = new URL("../src/tokens/", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens.json", dir), "utf8"));

const toVar = (path) => `--rb-${path.join("-")}`;
const resolve = (value) =>
  value.replace(/\{([^}]+)\}/g, (_, ref) => `var(${toVar(ref.split("."))})`);

const lines = [];
const walk = (node, path) => {
  for (const [key, value] of Object.entries(node)) {
    const next = [...path, key];
    if (typeof value === "object") walk(value, next);
    else lines.push(`  ${toVar(next)}: ${resolve(String(value))};`);
  }
};
walk(tokens, []);

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */\n:root {\n${lines.join("\n")}\n}\n`;
writeFileSync(fileURLToPath(new URL("tokens.css", dir)), css);
console.log(`tokens.css: ${lines.length} variables`);
